"""D4 step 3: low / medium / high risk tiers for the frozen trees model (exit_12m, raw probabilities; no calibration was applied).

Cutoffs are multiples of the TRAINING base rate (exit_12m, 2012-2018: 632 / 14,982 = 4.22%). Candidate multiples
{0.25, 0.5, 0.75, 1, 1.5, 2, 2.5, 3, 4} are scored on the validation predictions, and the cutoffs are chosen by rules written here:
  low / medium boundary  = the HIGHEST multiple whose low tier (score below the cutoff) has an observed validation exit rate <= 0.25 x base
  medium / high boundary = the LOWEST multiple whose high tier (score at or above it) has an observed validation exit rate >= 3.5 x base
Cutoffs are then rounded to 3 decimals so they can be hard-coded in the deployed app. Also reported: the same tiers per validation
year and on training out-of-fold predictions 2015-2018 (a check that the tiers are not an artifact of the validation years).
The test file is never read. Writes docs/risk_tiers.md and docs/risk_tiers.json (cutoffs read by the spec and the app).
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from common_model import DOCS, PROCESSED, feature_columns, load_rows, rows_for_label  # noqa: E402
import importlib.util  # noqa: E402

_s = importlib.util.spec_from_file_location("fv", Path(__file__).parent / "04_fairness_variant.py")
fv = importlib.util.module_from_spec(_s); _s.loader.exec_module(fv)

LABEL = "exit_12m"
MULTS = (0.25, 0.5, 0.75, 1, 1.5, 2, 2.5, 3, 4)


def tier(p, lo, hi):
    return np.where(p < lo, "low", np.where(p < hi, "medium", "high"))


def table(p, y, lo, hi, base):
    t = tier(p, lo, hi)
    rows = []
    for name in ("low", "medium", "high"):
        s = t == name
        rows.append({"tier": name, "n": int(s.sum()), "share": s.mean(), "exits": int(y[s].sum()), "rate": y[s].mean() if s.any() else np.nan,
                     "lift": y[s].mean() / base if s.any() else np.nan, "share_of_exits": y[s].sum() / y.sum()})
    return pd.DataFrame(rows)


def md(t):
    L = ["| Tier | Store-years | Share | Exits | Observed exit rate | vs base | Share of all exits |", "|---|---|---|---|---|---|---|"]
    for _, r in t.iterrows():
        L.append(f"| {r['tier']} | {r['n']:,} | {r['share']:.1%} | {r['exits']} | {r['rate']:.1%} | {r['lift']:.2f}x | {r['share_of_exits']:.0%} |")
    return L


def main():
    d = rows_for_label(load_rows(), LABEL)
    train = d[d["part"] == "train"]
    base = float(train[LABEL].mean()); assert abs(base - 632 / 14982) < 1e-9
    v = pd.read_parquet(PROCESSED / "val_predictions.parquet"); v = v[v["label_name"] == LABEL].reset_index(drop=True)
    p, y = v["p_hgb"].to_numpy(), v["y"].to_numpy().astype(int)

    cand = []
    for m in MULTS:
        c = m * base; s = p >= c
        cand.append({"mult": m, "cutoff": c, "above_n": int(s.sum()), "above_rate": y[s].mean(), "below_n": int((~s).sum()), "below_rate": y[~s].mean()})
    cand = pd.DataFrame(cand)
    lo_m = cand[cand["below_rate"] <= 0.25 * base]["mult"].max()
    hi_m = cand[cand["above_rate"] >= 3.5 * base]["mult"].min()
    lo, hi = round(lo_m * base, 3), round(hi_m * base, 3)

    oof_p, oof_y, oof_year = [], [], []
    feats = feature_columns()
    for k in fv.FOLDS:
        fit, ev = train[train["year"] < k], train[train["year"] == k]
        oof_p.append(fv.make_model(feats).fit(fit[feats], fit[LABEL]).predict_proba(ev[feats])[:, 1]); oof_y.append(ev[LABEL].to_numpy()); oof_year += [k] * len(ev)
    oof_p, oof_y = np.concatenate(oof_p), np.concatenate(oof_y)

    L = ["# Risk tiers (trees, exit_12m, raw probabilities)", "",
         "Generated by `src/model/06_risk_tiers.py`. Cutoffs are relative to the training base rate "
         f"({base:.2%} = 632 / 14,982 store-years, 2012-2018) and chosen on validation 2019-2021 with rules fixed in the script. The test file is not read.", "",
         "## Candidate cutoffs (validation)", "", "| Multiple of base | Cutoff | At/above: store-years | At/above: observed rate | Below: store-years | Below: observed rate |", "|---|---|---|---|---|---|"]
    for _, r in cand.iterrows():
        L.append(f"| {r['mult']}x | {r['cutoff']:.4f} | {r['above_n']:,} | {r['above_rate']:.1%} | {r['below_n']:,} | {r['below_rate']:.1%} |")
    L += ["", "Rules: low/medium boundary = highest multiple whose low tier has observed rate <= 0.25 x base "
          f"(<= {0.25*base:.2%}); medium/high boundary = lowest multiple whose high tier has observed rate >= 3.5 x base (>= {3.5*base:.1%}).", "",
          f"**Chosen: low < {lo_m}x base = {lo:.3f}; medium {lo:.3f} to < {hi:.3f}; high >= {hi_m}x base = {hi:.3f}.**", "",
          "## Validation 2019-2021 (the data the cutoffs were chosen on)", ""] + md(table(p, y, lo, hi, base))
    for yr in sorted(v["year"].unique()):
        s = (v["year"] == yr).to_numpy()
        L += ["", f"### Validation {yr}", ""] + md(table(p[s], y[s], lo, hi, base))
    L += ["", "## Training out-of-fold 2015-2018 (not used to choose the cutoffs)", ""] + md(table(oof_p, oof_y, lo, hi, base))
    L += ["", "Observed rates are on the same data the cutoffs were chosen on for validation (optimistic by construction); the out-of-fold block is the independent sanity check.", ""]
    (DOCS / "risk_tiers.md").write_text("\n".join(L), encoding="utf-8")
    (DOCS / "risk_tiers.json").write_text(json.dumps({"base_rate": base, "low_cutoff": lo, "high_cutoff": hi, "low_multiple": float(lo_m), "high_multiple": float(hi_m)}, indent=2))
    print("\n".join(L))


if __name__ == "__main__":
    main()
