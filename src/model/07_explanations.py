"""D4 step 4: exact per-feature contributions and top-3 plain-language reasons for the frozen trees model (exit_12m, 20 features).

Fits the model on 2012-2018 (frozen settings, same as the validation predictions) and checks, on train AND validation rows:
  1. baseline + sum(feature contributions) equals the model's raw score (max abs difference reported),
  2. the sigmoid of the raw score equals predict_proba,
  3. perturbing one feature changes only that feature's contribution (column-mapping check),
and shows the top-3 reasons for example validation store-years. Validation rows are used for display only; the test file is never read.
Writes docs/explanations.md.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
from common_model import DOCS, feature_columns, load_rows, rows_for_label  # noqa: E402
from explain import contributions, raw_score, reference_contributions, top_reasons  # noqa: E402
import importlib.util  # noqa: E402

_s = importlib.util.spec_from_file_location("fv", Path(__file__).parent / "04_fairness_variant.py")
fv = importlib.util.module_from_spec(_s); _s.loader.exec_module(fv)
LABEL = "exit_12m"


def main():
    d = rows_for_label(load_rows(), LABEL)
    tr, va = d[d["part"] == "train"], d[d["part"] == "validation"]
    F = feature_columns()
    m = fv.make_model(F).fit(tr[F], tr[LABEL])
    ref = reference_contributions(m, tr[F])

    checks = []
    for name, X in (("train 2012-2018", tr[F]), ("validation 2019-2021", va[F])):
        base, C = contributions(m, X)
        raw = raw_score(m, X)
        e1 = float(np.abs(base + C.sum(axis=1).to_numpy() - raw).max())
        e2 = float(np.abs(1 / (1 + np.exp(-raw)) - m.predict_proba(X)[:, 1]).max())
        assert e1 < 1e-9 and e2 < 1e-9, (name, e1, e2)
        checks.append((name, len(X), e1, e2))

    # column-mapping check: change one feature, only its contribution may move
    X0 = va[F].head(300).copy()
    _, C0 = contributions(m, X0)
    moved = {}
    for f in F:
        X1 = X0.copy()
        if f == "store_type":
            X1[f] = pd.Categorical(["Small Grocery Store"] * len(X1), categories=X0[f].cat.categories)
        else:
            X1[f] = X1[f].fillna(0) * 3 + 1
        _, C1 = contributions(m, X1)
        diff = (C1 - C0).abs().max()
        others = diff.drop(f).max()
        assert others < 1e-12, (f, diff[diff > 1e-12])
        moved[f] = float(diff[f])

    base, C = contributions(m, va[F])
    p = m.predict_proba(va[F])[:, 1]
    used = (C != 0).any()
    imp = C.abs().mean().sort_values(ascending=False)
    # centred effect = contribution minus the average training store's
    D = C - ref
    n_pos = (D > 1e-12).sum(axis=1)

    order = np.argsort(-p)
    pick = {"highest-scoring validation store-year": order[0], "10th highest": order[9], "median score": order[len(p) // 2],
            "lowest score": order[-1]}
    hi_exit = np.flatnonzero((va[LABEL].to_numpy() == 1) & (p > np.quantile(p, 0.95)))[:1]
    if len(hi_exit):
        pick["a top-5% store-year that did exit"] = hi_exit[0]
    reasons = top_reasons(m, va[F].iloc[list(pick.values())], ref)

    L = ["# Explanations: exact per-feature contributions (trees, exit_12m)", "",
         "Generated by `src/model/07_explanations.py`; implementation in `src/model/explain.py`. With `max_leaf_nodes=2` every one of the 300 boosting iterations is a "
         "stump splitting on one feature, so the model's raw score (log-odds) is exactly `baseline + sum of per-feature contributions`, where a feature's contribution is the "
         "sum of the leaf values of the stumps that split on it. Fitted on 2012-2018 with the frozen settings; the test file is not read.", "",
         f"Baseline (log-odds with every contribution at zero): {base:+.4f}. Features that the 300 stumps actually split on: {int(used.sum())} of {len(F)} "
         f"(never used: {', '.join(used.index[~used]) or 'none'}).", "", "## Verification", "",
         "| Rows | n | max abs(baseline + sum of contributions - raw score) | max abs(sigmoid(raw) - predict_proba) |", "|---|---|---|---|"]
    for name, n, e1, e2 in checks:
        L.append(f"| {name} | {n:,} | {e1:.1e} | {e2:.1e} |")
    L += ["", "Column-mapping check: for each of the 20 features, replacing its values changed only that feature's contribution (all others moved by < 1e-12).", "",
          "## Mean absolute contribution on validation (log-odds)", "", "| Feature | Mean abs contribution |", "|---|---|"]
    L += [f"| {f} | {v:.3f} |" for f, v in imp.items() if v > 0]
    L += ["", "## Top-3 reasons", "",
          "`top_reasons(model, X, reference, k=3)` ranks features by contribution **minus the average training store's contribution** (`reference`, the mean contribution over "
          "the 2012-2018 training rows) and keeps the largest positive ones, so a reason means 'pushes this store's risk above a typical store's'. Fewer than 3 are returned "
          f"when fewer features push risk up (on validation, {np.mean(n_pos >= 3):.0%} of rows have at least 3).", ""]
    for (label, _), r, i in zip(pick.items(), reasons, list(pick.values())):
        row = va.iloc[i]
        L += [f"**{label}** (record {row['record_id']}, cohort {int(row['year'])}, predicted {p[i]:.1%}, {'exited' if row[LABEL] else 'did not exit'}):"]
        L += [f"{k}. {x['text']}  [{x['feature']}, +{x['effect']:.2f} log-odds vs average store]" for k, x in enumerate(r, 1)] or ["_(no feature above the average store)_"]
        L += [""]
    (DOCS / "explanations.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
