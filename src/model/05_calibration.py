"""D4 step 2: calibration of the frozen trees model (20 features, exit_12m) on the existing validation predictions.

Validation predictions (p_hgb in data/processed/val_predictions.parquet, model fit on 2012-2018) are only DIAGNOSED here.
Rule written before looking: the model counts as miscalibrated if mean predicted / observed rate is outside 0.8-1.25 or the
calibration slope (logistic regression of y on logit p) is outside 0.7-1.3. If so, a Platt calibrator (logistic on logit p; two
parameters, chosen over isotonic because the data are small) is fit on training folds ONLY: out-of-fold predictions for 2015-2018
from the rolling folds (fit 2012..k-1, score k), then applied unchanged to the validation predictions. Test is never read.
Writes docs/calibration.md, docs/calibration_bins.csv, figures/calibration_curve.png.
"""

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import brier_score_loss

sys.path.insert(0, str(Path(__file__).parent))
from common_model import DOCS, FIGURES, PROCESSED, feature_columns, load_rows, rows_for_label  # noqa: E402
import importlib.util  # noqa: E402

_s = importlib.util.spec_from_file_location("fv", Path(__file__).parent / "04_fairness_variant.py")
fv = importlib.util.module_from_spec(_s); _s.loader.exec_module(fv)

LABEL = "exit_12m"
logit = lambda p: np.log(np.clip(p, 1e-6, 1 - 1e-6) / (1 - np.clip(p, 1e-6, 1 - 1e-6)))


def slope_intercept(p, y):
    lr = LogisticRegression(C=1e6, max_iter=1000).fit(logit(p).reshape(-1, 1), y)
    return float(lr.coef_[0, 0]), float(lr.intercept_[0])


def summarize(p, y):
    s, i = slope_intercept(p, y)
    return {"brier": brier_score_loss(y, p), "mean_pred": float(p.mean()), "observed": float(y.mean()), "slope": s, "intercept": i}


def bins(p, y, n=10):
    q = pd.qcut(p, n, duplicates="drop")
    return pd.DataFrame({"p": p, "y": y, "bin": q}).groupby("bin", observed=True).agg(n=("y", "size"), mean_pred=("p", "mean"), observed=("y", "mean")).reset_index(drop=True)


def main():
    d = rows_for_label(load_rows(), LABEL)
    train = d[d["part"] == "train"]
    v = pd.read_parquet(PROCESSED / "val_predictions.parquet")
    v = v[v["label_name"] == LABEL]
    p, y = v["p_hgb"].to_numpy(), v["y"].to_numpy().astype(int)
    before = summarize(p, y)
    ratio = before["mean_pred"] / before["observed"]
    miscal = not (0.8 <= ratio <= 1.25) or not (0.7 <= before["slope"] <= 1.3)

    # training-fold out-of-fold predictions (2015-2018)
    feats = feature_columns()
    oof_p, oof_y = [], []
    for k in fv.FOLDS:
        fit, ev = train[train["year"] < k], train[train["year"] == k]
        oof_p.append(fv.make_model(feats).fit(fit[feats], fit[LABEL]).predict_proba(ev[feats])[:, 1]); oof_y.append(ev[LABEL].to_numpy())
    oof_p, oof_y = np.concatenate(oof_p), np.concatenate(oof_y)
    oof = summarize(oof_p, oof_y)
    plat = LogisticRegression(C=1e6, max_iter=1000).fit(logit(oof_p).reshape(-1, 1), oof_y)
    pc = plat.predict_proba(logit(p).reshape(-1, 1))[:, 1]
    after = summarize(pc, y)
    pd.concat([bins(p, y).assign(version="before"), bins(pc, y).assign(version="after (Platt, train folds)"),
               bins(oof_p, oof_y).assign(version="train out-of-fold")]).to_csv(DOCS / "calibration_bins.csv", index=False)

    fig, ax = plt.subplots(figsize=(5, 5))
    for lab, pp, yy in (("validation, raw", p, y), ("validation, Platt (train folds)", pc, y), ("train out-of-fold, raw", oof_p, oof_y)):
        b = bins(pp, yy); ax.plot(b["mean_pred"], b["observed"], "o-", label=lab)
    m = max(0.15, float(bins(p, y)["observed"].max()))
    ax.plot([0, m], [0, m], ":", c="grey"); ax.set_xlabel("Mean predicted (decile bins)"); ax.set_ylabel("Observed exit rate")
    ax.set_title("Calibration, exit_12m trees"); ax.legend(fontsize=8); fig.tight_layout(); fig.savefig(FIGURES / "calibration_curve.png", dpi=150)

    f = lambda r: f"| {r['brier']:.4f} | {r['mean_pred']:.2%} | {r['observed']:.2%} | {r['slope']:.2f} | {r['intercept']:+.2f} |"
    L = ["# Calibration (trees, exit_12m)", "", "Generated by `src/model/05_calibration.py`. Validation 2019-2021 (model fit on 2012-2018) is diagnosed only; the test file is not read.",
         "Rule (set before looking): miscalibrated if mean predicted / observed is outside 0.8-1.25 or slope outside 0.7-1.3.", "",
         "| Predictions | Brier | Mean predicted | Observed | Slope | Intercept |", "|---|---|---|---|---|---|",
         f"| Validation, raw {f(before)}", f"| Validation, Platt fit on training folds {f(after)}", f"| Training out-of-fold 2015-2018, raw {f(oof)}", "",
         f"Mean predicted / observed on validation: {ratio:.2f}; slope {before['slope']:.2f}. **Miscalibrated by the rule: {'yes' if miscal else 'no'}.**",
         "**Decision: no calibration is applied** (rule not met; the Platt column is shown for reference and would not help: Brier 0.0321 -> 0.0322, mean predicted 3.48% -> 3.79%).",
         f"Platt on training folds: logit(p') = {plat.intercept_[0]:+.3f} + {plat.coef_[0,0]:.3f} * logit(p), fit on {len(oof_y):,} out-of-fold store-years ({int(oof_y.sum())} exits).", "",
         "Validation decile bins (raw -> Platt) are in `docs/calibration_bins.csv`; plot `figures/calibration_curve.png`.", ""]
    b0, b1 = bins(p, y), bins(pc, y)
    L += ["| Bin | n | Raw mean pred | Platt mean pred | Observed (same stores, raw bins) |", "|---|---|---|---|---|"]
    for i in range(len(b0)):
        L.append(f"| {i+1} | {b0['n'][i]} | {b0['mean_pred'][i]:.2%} | {b1['mean_pred'][i]:.2%} | {b0['observed'][i]:.2%} |")
    (DOCS / "calibration.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L)); print(f"PLATT a={plat.intercept_[0]:.4f} b={plat.coef_[0,0]:.4f}")


if __name__ == "__main__":
    main()
