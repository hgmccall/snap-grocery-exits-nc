"""D4 fairness check: trees with vs without tract demographic features (pre-registered in docs/changes_since_d3.md).

Selection uses ONLY the mean PR-AUC over the rolling training folds inside 2012-2018 (fit 2012..k-1, score k, k = 2015-2018),
frozen trees settings, label exit_12m. Validation 2019-2021 is scored for both versions as report-only. The test file is never
read. Group false-positive rates use the same flag as 02_error_analysis.py (top 50 statewide per cohort year) and the same tract
majority definition (a bias_* share > 0.5); bias_* columns define groups only, never inputs.

Writes docs/fairness_variant.md, docs/fairness_variant.csv, data/processed/val_predictions_nodemo.parquet (gitignored).
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import average_precision_score
from sklearn.pipeline import Pipeline

sys.path.insert(0, str(Path(__file__).parent))
from common_model import DOCS, PROCESSED, SEED, TOP_K_STATE, feature_columns, load_rows, rows_for_label, top_k_flags  # noqa: E402

LABEL = "exit_12m"
FROZEN = dict(lr=0.1, leaves=2, min_leaf=100, l2=0.0)
DEMOGRAPHIC = ["pct_poverty", "median_hh_income", "pct_snap_hh", "pct_no_vehicle", "pct_renter", "unemployment_rate", "pct_age_65_plus"]
FULL = feature_columns()
NODEMO = [c for c in FULL if c not in DEMOGRAPHIC]
assert len(NODEMO) == len(FULL) - len(DEMOGRAPHIC)
FOLDS = (2015, 2016, 2017, 2018)
REFERENCE, MARGIN = 0.155, 0.005


class ImputeUnemployment:
    """Same as 01_evaluate.ImputeUnemployment: median fitted on the rows passed to fit (NaN would mark cohort 2012)."""
    COL = "unemployment_rate"

    def fit(self, X, y=None):
        self.median_ = float(X[self.COL].median()); return self

    def transform(self, X):
        X = X.copy(); X[self.COL] = X[self.COL].fillna(self.median_); return X

    def fit_transform(self, X, y=None):
        return self.fit(X, y).transform(X)

    def get_params(self, deep=True): return {}
    def set_params(self, **p): return self


def make_model(features):
    steps = [("unemp", ImputeUnemployment())] if "unemployment_rate" in features else []
    steps.append(("hgb", HistGradientBoostingClassifier(
        learning_rate=FROZEN["lr"], max_leaf_nodes=FROZEN["leaves"], min_samples_leaf=FROZEN["min_leaf"],
        l2_regularization=FROZEN["l2"], max_iter=300, early_stopping=False,
        categorical_features="from_dtype", random_state=SEED)))
    return Pipeline(steps)


def majority(v):
    r = v[["bias_pct_white_nh", "bias_pct_black_nh", "bias_pct_hispanic"]]
    m = pd.Series("Other/none", index=v.index)
    for c, n in (("bias_pct_white_nh", "White"), ("bias_pct_black_nh", "Black"), ("bias_pct_hispanic", "Hispanic")):
        m[r[c] > 0.5] = n
    m[r.isna().all(axis=1)] = "Missing"
    return m


def main():
    d = rows_for_label(load_rows(), LABEL)
    train, val = d[d["part"] == "train"], d[d["part"] == "validation"].copy()
    out, preds = [], val[["record_id", "year", LABEL]].copy()
    grp = majority(val)
    y = val[LABEL].astype(bool)
    for name, feats in (("with demographics (current)", FULL), ("without demographics", NODEMO)):
        folds = []
        for k in FOLDS:
            fit, ev = train[train["year"] < k], train[train["year"] == k]
            folds.append(average_precision_score(ev[LABEL], make_model(feats).fit(fit[feats], fit[LABEL]).predict_proba(ev[feats])[:, 1]))
        p = make_model(feats).fit(train[feats], train[LABEL]).predict_proba(val[feats])[:, 1]
        preds[name] = p
        flag = top_k_flags(pd.Series(p, index=val.index), val["year"], TOP_K_STATE)
        row = {"version": name, "n_features": len(feats), "fold_mean": float(np.mean(folds)),
               **{f"fold_{k}": f for k, f in zip(FOLDS, folds)}, "val_pr_auc": average_precision_score(val[LABEL], p)}
        for g in ("Black", "White"):
            i = grp == g
            row[f"fpr_{g}"] = float((flag & ~y & i).sum() / (~y & i).sum())
            row[f"flagged_{g}"] = int((flag & i).sum()); row[f"nonexits_{g}"] = int((~y & i).sum())
            row[f"exits_{g}"] = int((y & i).sum()); row[f"caught_{g}"] = int((flag & y & i).sum())
        out.append(row)
    res = pd.DataFrame(out)
    res.to_csv(DOCS / "fairness_variant.csv", index=False)
    preds.to_parquet(PROCESSED / "val_predictions_nodemo.parquet", index=False)

    a, b = res.iloc[0], res.iloc[1]
    gap = a["fold_mean"] - b["fold_mean"]
    prefer = (b["fold_mean"] >= REFERENCE - MARGIN)  # pre-registered: within 0.005 of 0.155 (the reference, not the recomputed value)
    L = ["# Fairness check: trees without tract demographic features", "",
         "Generated by `src/model/04_fairness_variant.py`. Pre-registered rule in `docs/changes_since_d3.md`: prefer the variant if its mean "
         f"training-fold PR-AUC (folds 2015-2018, `exit_12m`, frozen settings) is within {MARGIN} of {REFERENCE}, i.e. >= {REFERENCE - MARGIN:.3f}.",
         f"Removed ({len(DEMOGRAPHIC)}): {', '.join(DEMOGRAPHIC)}. Remaining {len(NODEMO)} features: {', '.join(NODEMO)}.", "",
         "| Version | Features | Fold PR-AUC 2015 / 2016 / 2017 / 2018 | **Mean fold PR-AUC** | Val PR-AUC (report only) | FPR majority-Black | FPR majority-White |",
         "|---|---|---|---|---|---|---|"]
    for _, r in res.iterrows():
        L.append(f"| {r['version']} | {r['n_features']} | {' / '.join(f'{r[f'fold_{k}']:.3f}' for k in FOLDS)} | **{r['fold_mean']:.4f}** | {r['val_pr_auc']:.3f} | "
                 f"{r['fpr_Black']:.1%} ({r['flagged_Black']} flagged / {r['nonexits_Black']} non-exits) | {r['fpr_White']:.1%} ({r['flagged_White']} / {r['nonexits_White']}) |")
    L += ["", f"Exits in validation: majority-Black {int(a['exits_Black'])}, majority-White {int(a['exits_White'])}. FPR = non-exits flagged in the top 50 per year / non-exits "
          "in the group, validation 2019-2021.", "",
          f"Gap in mean fold PR-AUC (current minus variant): {gap:+.4f}. Variant mean {b['fold_mean']:.4f} vs threshold {REFERENCE - MARGIN:.3f}.", "",
          f"**Decision: {'variant WITHOUT demographics is preferred' if prefer else 'keep the current model WITH demographics'}.**", ""]
    (DOCS / "fairness_variant.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
